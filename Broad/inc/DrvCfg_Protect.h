/* 功能域，用于状态机按域查询：PV 故障不拦 INV，反之亦然 */
typedef enum
{
    PROTECT_DOMAIN_INV = 0,
    PROTECT_DOMAIN_PV,
    PROTECT_DOMAIN_GRID,
    PROTECT_DOMAIN_DC,
    PROTECT_DOMAIN_SYS,
    PROTECT_DOMAIN_NUM
}E_PROTECT_DOMAIN;

/* 严重度，同时用作动作等级：数值越大动作越强 */
typedef enum
{
    PROTECT_SEV_INFO = 0,       /* 只提示，不停机 */
    PROTECT_SEV_WARN,           /* 告警，不动作 */
    PROTECT_SEV_DERATE,         /* 降额运行 */
    PROTECT_SEV_STOP,           /* 封锁发波、断继电器 */
    PROTECT_SEV_TRIP,           /* 硬件级跳闸，必须复位 */
    PROTECT_SEV_NUM
}E_PROTECT_SEV;

/* 恢复方式 */
typedef enum
{
    PROTECT_REC_AUTO = 0,       /* 判据消失即自动恢复 */
    PROTECT_REC_CMD,            /* 记录锁存，需上位机或本地复位 */
    PROTECT_REC_POWER           /* 记录锁存，需重新上电 */
}E_PROTECT_RECOVER;

typedef struct
{
    Uint16 u16Word;             /* 内部故障字第号 PROTECT_W_xxx */
    Uint16 u16Mask;             /* 该字内的位掩码，单 bit */
    Uint16 u16DebounceMs;       /* 判据持续时间，0 表示立即 */
    Uint16  u16Domain;            /* E_PROTECT_DOMAIN */
    Uint16  u16Severity;          /* E_PROTECT_SEV */
    Uint16  u16Recover;           /* E_PROTECT_RECOVER */
    Uint16  u16Reserved;
}ST_PROTECT_ATTR;

/* 一个协议位到若干内部位的 any-of 关系 */
typedef struct
{
    Uint16  u16ProtoWord;         /* PROTECT_PW_xxx */
    Uint16  u16ProtoBit;          /* 0~15 */
    Uint16  u16SrcNum;            /* 1~PROTECT_AGG_SRC_NUM */
    Uint16  u16Reserved;
    Uint16  u16SrcWord[PROTECT_AGG_SRC_NUM];
    Uint16 u16SrcMask[PROTECT_AGG_SRC_NUM];
}ST_PROTECT_AGG_ITEM;

typedef struct
{
    const ST_PROTECT_ATTR     *pstAttr;
    Uint16                     u16FaultNum;
    const ST_PROTECT_AGG_ITEM *pstAgg;
    Uint16                     u16AggNum;
}ST_PROTECT_CFG;

